// Writes src/core/abi.ts from the Foundry build output. Run after `forge build`.
import { readFileSync, writeFileSync } from "node:fs";
const out = ["Leash", "PayeeRegistry"]
  .map((n) => {
    const { abi } = JSON.parse(readFileSync(`contracts/out/${n}.sol/${n}.json`, "utf8"));
    return `export const ${n[0].toLowerCase() + n.slice(1)}Abi = ${JSON.stringify(abi)} as const;`;
  })
  .join("\n\n");
writeFileSync("src/core/abi.ts", `// Generated by scripts/gen-abi.mjs. Do not edit.\n${out}\n`);
